class Solution {
    public long countCommas(long n) {
        //int n = n.String.valueOf(n).length();

        if(n < 1000)
            return 0;
        if(n<=999999)
            return n - 999;
        if(n<=999999999)
            return 999999 - 999 +  2 * (n - 999999);
        if( n<=999999999999L){
            return 999999 - 999 +  2 * (999999999 - 999999) + 3*( n - 999999999);
        }
        if(n <= 999999999999999L){
            return 999999 - 999 +  2 * (999999999 - 999999) + 3*( 999999999999L - 999999999) + 4*(n - 999999999999L);
        }
        return 999999 - 999 +  2 * (999999999 - 999999) + 3*( 999999999999L - 999999999) + 4*(999999999999999L - 999999999999L) + 5*(n - 999999999999999L);

        
        
    }
}
